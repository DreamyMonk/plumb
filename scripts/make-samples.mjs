// Generates deliberately messy sample files in public/samples. Seeded, so output is stable.
import fs from "node:fs";
import path from "node:path";

let seed = 20260105;
const random = () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const pick = (list) => list[Math.floor(random() * list.length)];
const weighted = (pairs) => {
  const total = pairs.reduce((sum, [, w]) => sum + w, 0);
  let r = random() * total;
  for (const [value, w] of pairs) {
    r -= w;
    if (r <= 0) return value;
  }
  return pairs[0][0];
};
const gaussian = () => Math.sqrt(-2 * Math.log(1 - random())) * Math.cos(2 * Math.PI * random());
const csv = (value) => (/[",\n]/.test(String(value)) ? `"${String(value).replace(/"/g, '""')}"` : String(value));

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const pad = (n) => String(n).padStart(2, "0");

function messyDate(d) {
  const [y, m, day] = [d.getUTCFullYear(), d.getUTCMonth() + 1, d.getUTCDate()];
  return weighted([
    [`${y}-${pad(m)}-${pad(day)}`, 6],
    [`${m}/${day}/${y}`, 3],
    [`${MONTHS[m - 1]} ${day}, ${y}`, 1],
  ]);
}

const PRODUCTS = {
  Electronics: [["Wireless Earbuds", 79], ["Smart Speaker", 129], ["4K Monitor", 349], ["Laptop Stand", 49]],
  Home: [["Air Purifier", 189], ["Desk Lamp", 39], ["Throw Blanket", 45], ["Ceramic Planter", 29]],
  Outdoors: [["Trail Backpack", 119], ["Camp Stove", 69], ["Insulated Bottle", 32], ["Hammock", 59]],
  Office: [["Ergonomic Chair", 299], ["Notebook Set", 18], ["Whiteboard", 64], ["Label Maker", 42]],
};
const REGION_WEIGHT = [["North", 3], ["South", 2.2], ["East", 2.6], ["West", 4]];
const REGION_NOISE = { North: ["north", "NORTH", " North", "Nrth"], South: ["south", "SOUTH", "Soth"], East: ["east", "EAST", "East "], West: ["west", "WEST", " West "] };

function retailOrders() {
  const start = Date.UTC(2023, 0, 1);
  const end = Date.UTC(2026, 8, 18); // stops mid-month on purpose
  const rows = [];
  for (let t = start; t <= end; t += 86_400_000) {
    const d = new Date(t);
    const years = (t - start) / (365.25 * 86_400_000);
    const month = d.getUTCMonth();
    const seasonal = 1 + 0.35 * Math.cos((2 * Math.PI * (month - 11)) / 12);
    const weekend = d.getUTCDay() === 0 || d.getUTCDay() === 6 ? 1.25 : 1;
    const iso = d.toISOString().slice(0, 10);
    const promo = iso === "2025-11-28"; // Black Friday: a burst of discounted online electronics
    const orders = Math.round(13 * (1 + 0.22 * years) * seasonal * weekend * (promo ? 7 : 1) + gaussian());
    for (let i = 0; i < Math.max(0, orders); i++) {
      const onPromo = promo && random() < 0.85;
      const category = onPromo ? "Electronics" : weighted([["Electronics", 4], ["Home", 3], ["Outdoors", month >= 4 && month <= 8 ? 4 : 1.5], ["Office", 2]]);
      const [product, price] = pick(PRODUCTS[category]);
      const region = weighted(REGION_WEIGHT);
      const channel = onPromo ? "Online" : weighted([["Online", 5 + years], ["Retail", 4], ["Partner", 1.5]]);
      if (iso === "2026-03-12" && channel === "Online") continue; // checkout outage (logged)
      if (iso === "2026-07-08" && region === "West") continue; // West warehouse closed (not logged)
      const qty = 1 + Math.floor(random() ** 2.4 * 5);
      const discount = onPromo ? 25 : weighted([[0, 6], [5, 2], [10, 2], [15, 1], [25, 0.4]]);
      const unit = Math.round(price * (1 + gaussian() * 0.03) * 100) / 100;
      const revenue = Math.round(qty * unit * (1 - discount / 100) * 100) / 100;
      rows.push({ date: d, category, product, region, channel, qty, unit, discount, revenue, returned: random() < (category === "Electronics" ? 0.09 : 0.04) });
    }
  }

  const header = ["Order ID", "Order Date", "Customer ID", "Region", "Category", "Product", "Qty", "Unit Price", "Discount %", "Revenue", "Channel", "Returned", "Internal Notes"];
  const lines = ["Northwind Goods — Sales Export", "Generated by ERP v4.2", "", header.join(",")];
  rows.forEach((row, index) => {
    const cells = [
      `SO-${100000 + index}`,
      messyDate(row.date),
      `C${String(1 + Math.floor(random() * 800)).padStart(4, "0")}`,
      random() < 0.06 ? pick(REGION_NOISE[row.region]) : row.region,
      row.category,
      row.product,
      random() < 0.012 ? "N/A" : random() < 0.0012 ? 999 : row.qty,
      `$${row.unit.toFixed(2)}`,
      `${row.discount}%`,
      random() < 0.015 ? "-" : `$${row.revenue.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
      random() < 0.02 ? "" : row.channel,
      row.returned ? "Yes" : "No",
      "",
    ];
    const line = cells.map(csv).join(",");
    lines.push(line);
    if (random() < 0.01) lines.push(line); // exact duplicate
    if (index > 0 && index % 10000 === 0) lines.push(header.join(",")); // repeated page header
  });
  const total = rows.reduce((sum, row) => sum + row.revenue, 0);
  lines.push(["Total", "", "", "", "", "", "", "", "", `"$${total.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}"`, "", "", ""].join(","));
  return lines.join("\n");
}

// Made-up people. Phone numbers use 555-01xx, which is reserved for fiction.
const FIRST = ["Ada", "Grace", "Alan", "Linus", "Margaret", "Dennis", "Barbara", "Ken", "Radia", "Tim", "Katherine", "Guido", "Frances", "Vint", "Hedy", "Edsger", "Annie", "Bjarne", "Sophie", "Conan"];
const LAST = ["Lovelace", "Hopper", "Turing", "Torvalds", "Hamilton", "Ritchie", "Liskov", "Thompson", "Perlman", "Berners", "Johnson", "Rossum", "Allen", "Cerf", "Lamarr", "Dijkstra", "Easley", "Stroustrup", "Wilson", "O'Brien"];

function customers() {
  const lines = [["Customer ID", "Full Name", "Email", "Phone", "Signup Date", "Plan", "Monthly Spend", "Support Tickets", "Tenure Months", "Region", "NPS", "Churned"].join(",")];
  for (let i = 1; i <= 800; i++) {
    const first = FIRST[i % FIRST.length];
    const last = LAST[Math.floor(i / FIRST.length) % LAST.length];
    const email = `${first}.${last.replace(/'/g, "")}${i}@example.com`.toLowerCase();
    const area = ["212", "415", "312", "617", "206", "512", "303", "404", "702", "919"][Math.floor(i / 100) % 10];
    const phone = `+1 (${area}) 555-01${String(i % 100).padStart(2, "0")}`;
    const plan = weighted([["Basic", 5], ["Plus", 3], ["Pro", 2]]);
    const spend = { Basic: 29, Plus: 79, Pro: 199 }[plan] * (1 + gaussian() * 0.08);
    const tenure = 1 + Math.floor(random() * 46);
    const tickets = Math.floor(random() ** 2 * 9);
    const nps = Math.max(0, Math.min(10, Math.round(8 - tickets * 0.55 + gaussian() * 1.4)));
    const risk = -0.9 + tickets * 0.42 - tenure * 0.055 - (plan === "Pro" ? 0.8 : plan === "Plus" ? 0.3 : 0) - (nps - 6) * 0.28;
    const churned = random() < 1 / (1 + Math.exp(-risk));
    const signup = new Date(Date.UTC(2026, 8, 1) - tenure * 30.4 * 86_400_000);
    lines.push(
      [
        `C${String(i).padStart(4, "0")}`,
        `${first} ${last}`,
        email,
        phone,
        messyDate(signup),
        random() < 0.05 ? plan.toUpperCase() : plan,
        random() < 0.03 ? "" : `$${spend.toFixed(2)}`,
        tickets,
        tenure,
        weighted(REGION_WEIGHT),
        random() < 0.08 ? "n/a" : nps,
        churned ? "Yes" : "No",
      ].map(csv).join(","),
    );
  }
  return lines.join("\n");
}

const out = path.join(import.meta.dirname, "..", "public", "samples");
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "retail_orders.csv"), retailOrders());
fs.writeFileSync(path.join(out, "customers.csv"), customers());
console.log("wrote samples to", out);
